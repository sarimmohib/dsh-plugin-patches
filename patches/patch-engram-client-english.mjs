function decodeEscapes(s) {
  return s
    .replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/\\x([0-9a-fA-F]{2})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function encodeNonAscii(s) {
  let out = "";
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp < 0x7f) out += ch;
    else if (cp <= 0xffff) out += "\\u" + cp.toString(16).padStart(4, "0");
    else {
      const v = cp - 0x10000;
      const hi = 0xd800 + (v >> 10);
      const lo = 0xdc00 + (v & 0x3ff);
      out += "\\u" + hi.toString(16).padStart(4, "0") + "\\u" + lo.toString(16).padStart(4, "0");
    }
  }
  return out;
}

const sorted = [...MAP].sort((a, b) => b[0].length - a[0].length);
let failures = 0;

for (const dir of process.argv.slice(2)) {
  const file = join(dir, "lib", "client.js");
  if (!existsSync(file)) {
    console.log(`skip (no client bundle): ${dir}`);
    continue;
  }
  const raw = readFileSync(file, "utf8");
  const decoded = decodeEscapes(raw);
  const remainingBefore = (decoded.match(/[\u4e00-\u9fff]/g) || []).length;
  if (remainingBefore === 0) {
    console.log(`skip (already English): ${file}`);
    continue;
  }

  let text = decoded;
  let applied = 0;
  const missed = [];
  for (const [zh, en] of sorted) {
    if (text.includes(zh)) {
      text = text.split(zh).join(en);
      applied += 1;
    } else if (!raw.includes(encodeNonAscii(zh))) {
      missed.push(zh.slice(0, 40));
    }
  }

  const left = (text.match(/[\u4e00-\u9fff]/g) || []).length;
  writeFileSync(file, encodeNonAscii(text), "utf8");
  console.log(`patched: ${file}`);
  console.log(`  keys applied = ${applied}, CJK before = ${remainingBefore}, CJK after = ${left}`);
  if (missed.length) {
    console.log(`  anchors not present (${missed.length}): ${missed.slice(0, 10).join(" | ")}`);
  }
  if (left > 0) {
    failures += 1;
    const sample = [...new Set(text.match(/[\u4e00-\u9fff]+/g) || [])].slice(0, 25);
    console.log(`  REMAINING: ${sample.join(" / ")}`);
  }
}

if (failures > 0) {
  console.log(`\n${failures} bundle(s) still contain Chinese.`);
  process.exitCode = 1;
} else {
  console.log("\nengram client english patch complete");
}
